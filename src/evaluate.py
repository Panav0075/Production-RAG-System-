from pathlib import Path
import json
import statistics
import yaml

from .metrics import hit_at_k, keyword_coverage, reciprocal_rank, token_f1
from .rag import RAGSystem


STRATEGIES = ["lexical", "semantic", "hybrid"]


def evaluate_strategy(rag, qa_pairs, strategy):
    examples = []

    for qa in qa_pairs:
        result = rag.ask(qa["question"], strategy=strategy)
        retrieved = result["retrieved_chunks"]

        metrics = {
            "hit_at_1": hit_at_k(retrieved, qa["expected_source"], 1),
            "hit_at_3": hit_at_k(retrieved, qa["expected_source"], 3),
            "reciprocal_rank": reciprocal_rank(retrieved, qa["expected_source"]),
            "answer_f1": token_f1(result["answer"], qa["expected_answer"]),
            "keyword_coverage": keyword_coverage(result["answer"], qa["keywords"]),
        }

        examples.append(
            {
                "question": qa["question"],
                "expected_source": qa["expected_source"],
                "predicted_answer": result["answer"],
                "top_source": retrieved[0]["source"] if retrieved else None,
                "metrics": metrics,
            }
        )

    summary = {}
    for metric in [
        "hit_at_1",
        "hit_at_3",
        "reciprocal_rank",
        "answer_f1",
        "keyword_coverage",
    ]:
        summary[metric] = round(
            statistics.mean(example["metrics"][metric] for example in examples),
            4,
        )

    return {"summary": summary, "examples": examples}


def write_markdown(results, path):
    lines = [
        "# Retrieval Evaluation",
        "",
        "Generated by `python -m src.evaluate`.",
        "",
        "The same QA set is evaluated against each retrieval strategy.",
        "",
        "| Strategy | Hit@1 | Hit@3 | MRR | Answer F1 | Keyword Coverage |",
        "|---|---:|---:|---:|---:|---:|",
    ]

    for strategy, result in results.items():
        s = result["summary"]
        lines.append(
            f"| {strategy.title()} | {s['hit_at_1']:.3f} | "
            f"{s['hit_at_3']:.3f} | {s['reciprocal_rank']:.3f} | "
            f"{s['answer_f1']:.3f} | {s['keyword_coverage']:.3f} |"
        )

    lines.extend(
        [
            "",
            "## How to read the table",
            "",
            "- **Hit@1**: expected source was the first retrieved result.",
            "- **Hit@3**: expected source appeared in the first three results.",
            "- **MRR**: rewards ranking the expected source near the top.",
            "- **Answer F1**: token overlap between generated and reference answers.",
            "- **Keyword Coverage**: fraction of required answer facts found in the generated answer.",
            "",
            "These metrics are useful for regression testing retrieval changes. They are not a substitute for human review of answer correctness, faithfulness, safety, or usefulness.",
        ]
    )

    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    with open("config.yaml", "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)

    qa_pairs = json.loads(
        Path(cfg["evaluation"]["qa_path"]).read_text(encoding="utf-8")
    )

    rag = RAGSystem.from_config("config.yaml")
    results = {}

    for strategy in STRATEGIES:
        results[strategy] = evaluate_strategy(rag, qa_pairs, strategy)

    output_json = Path(cfg["evaluation"]["output_json"])
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(results, indent=2), encoding="utf-8")

    write_markdown(results, cfg["evaluation"]["output_markdown"])

    for strategy in STRATEGIES:
        print(strategy, results[strategy]["summary"])


if __name__ == "__main__":
    main()
